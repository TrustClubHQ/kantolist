/**
 * Every user-facing string, in both languages.
 *
 * KantoList is read in San Ildefonso, where people talk in Taglish: Tagalog
 * sentences with the English words nobody translates — *listing*, *rent*,
 * *reserved*, *Trust Points*. The `tl` column is written that way on purpose.
 * A formal Tagalog rendering ("tala ng paninda") is not what anyone says, and
 * reads as a machine translation of a site that is supposed to feel local.
 *
 * This module has no `'use client'` and imports nothing from React, because
 * both sides need it: server components translate during the render, and
 * `LanguageProvider` hands the same dictionary to the client ones.
 */

export type Language = 'en' | 'tl'

export const LANGUAGES: Language[] = ['en', 'tl']

/** Written by the language toggle, read by every server component. */
export const LANGUAGE_COOKIE = 'language'

/**
 * Taglish is the default: this is a marketplace for one Bulacan town, and
 * English is the setting you switch to, not the one you arrive in.
 */
export const DEFAULT_LANGUAGE: Language = 'tl'

export function asLanguage(value: string | null | undefined): Language {
  return value === 'en' || value === 'tl' ? value : DEFAULT_LANGUAGE
}

export const LANGUAGE_LABEL: Record<Language, string> = {
  en: 'English',
  tl: 'Taglish',
}

/** Short form for the header toggle, where there is no room for a word. */
export const LANGUAGE_SHORT: Record<Language, string> = {
  en: 'EN',
  tl: 'TL',
}

export type Vars = Record<string, string | number>

/**
 * Look up a key, with `{name}` placeholders filled in.
 *
 * An unknown key falls back to English and then to the key itself, which is
 * ugly on screen and therefore gets noticed and fixed — the alternative,
 * rendering nothing, hides the gap.
 */
export function translate(language: Language, key: string, vars?: Vars): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}

export type T = (key: string, vars?: Vars) => string

/**
 * A category's name in the reader's language.
 *
 * Categories live in the database, so the stored name is the fallback: a
 * category added later shows up in English rather than as a missing key.
 */
export function categoryName(t: T, slug: string, stored: string): string {
  // A slug with its own entry wins, so the catch-all group's leaf can say
  // something more useful than its group already does.
  const own = t(`category.${slug}`)
  if (own !== `category.${slug}`) return own
  // Otherwise every group's escape-hatch leaf is named the same thing, and
  // gets one key rather than nine identical ones. The group it sits under is
  // always in view — the picker's optgroup, the filter rail's heading — so
  // the name does not have to repeat it.
  if (slug.startsWith('other-')) return t('category.other')
  return stored
}

/** The same, for an attribute's label on a category schema. */
/**
 * The example to show in the title box for a category.
 *
 * Falls back to the generic prompt rather than another category's example: a
 * category added later should ask "what is it?", not suggest tilapia.
 */
export function categoryExample(t: T, slug: string | undefined): string {
  if (!slug) return t('example.default')
  const example = t(`example.${slug}`)
  return example === `example.${slug}` ? t('example.default') : example
}

export function attributeLabel(t: T, key: string, stored: string): string {
  return orStored(t, `attr.${key}`, stored)
}

/**
 * Category slugs whose name matches a search word, in either language.
 *
 * Someone searching in Taglish types "sasakyan", not "vehicles" — and even in
 * English, "appliances" only ever matched listings that happened to use the
 * word in their title. The names are in the dictionary rather than the
 * database, so the match has to start here.
 */
export function categorySlugsMatching(query: string): string[] {
  const needle = query.trim().toLowerCase()
  if (needle.length < 2) return []
  const slugs = new Set<string>()
  for (const dictionary of Object.values(dictionaries)) {
    for (const [key, value] of Object.entries(dictionary)) {
      if (!key.startsWith('category.')) continue
      if (value.toLowerCase().includes(needle)) slugs.add(key.slice('category.'.length))
    }
  }
  return [...slugs]
}

function orStored(t: T, key: string, stored: string): string {
  const translated = t(key)
  return translated === key ? stored : translated
}

export function translatorFor(language: Language): T {
  return (key, vars) => translate(language, key, vars)
}

